#!/bin/sh
# Writes examples/voltty/core/term/width.tach: the display width of every code
# point, as unicode-width 0.2.2's `UnicodeWidthChar::width` (the crate
# alacritty_terminal 0.26 measures with), from the oracle's
# `voltty-oracle width-table` (ranges `lo hi w`, w one of 0 1 2 n).
#
# usage: examples/voltty/core/bench/gen-width.sh   (needs cargo, once)
#
# A two-level table: the high bits of a code point (c >> 8) choose a
# block of 256 two-bit widths (0, 1, 2, 3 for none), blocks shared.
# 0.20: replaced by std::text's width (A20).
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ORACLE="$HERE/../oracle"
(cd "$ORACLE" && cargo build --release --quiet)
"$ORACLE/target/release/voltty-oracle" width-table | awk '
function hexval(s,    i, c, v) {
    v = 0
    for (i = 1; i <= length(s); i++) {
        c = index("0123456789abcdef", substr(s, i, 1)) - 1
        v = v * 16 + c
    }
    return v
}
{
    lo = hexval($1); hi = hexval($2)
    code = ($3 == "n") ? 3 : $3 + 0
    for (c = lo; c <= hi; c++) w[c] = code
}
END {
    nblocks = 0
    for (b = 0; b < 4352; b++) {
        key = ""
        for (k = 0; k < 64; k++) {
            byte = 0
            for (j = 3; j >= 0; j--) byte = byte * 4 + w[b * 256 + k * 4 + j]
            bytes[k] = byte
            key = key byte ","
        }
        if (!(key in id)) {
            id[key] = nblocks
            for (k = 0; k < 64; k++) blockbytes[nblocks, k] = bytes[k]
            nblocks++
        }
        stage1[b] = id[key]
    }
    print "// Generated by examples/voltty/core/bench/gen-width.sh from unicode-width 0.2.2"
    print "// (the widths alacritty_terminal 0.26 uses): do not edit."
    print "//"
    print "// `width(c)`: 0 (combining), 1, 2 (wide), or -1 for none (controls)."
    print "// A two-level table: STAGE1[c >> 8] is a block of STAGE2, 64 bytes of"
    print "// four two-bit widths each (3 for none)."
    print "//"
    print "// 0.20: replaced by the display width of std::text (the design: A20)."
    print ""
    print "pub fn width(c: u32) -> i64 {"
    print "    if c >= 0x20 && c < 0x7F {"
    print "        return 1;"
    print "    }"
    print "    if c >= 0x110000 {"
    print "        return 1;"
    print "    }"
    print "    let block = STAGE1[(c >> 8) as i64] as i64;"
    print "    let byte = STAGE2[block * 64 + ((c & 0xFF) >> 2) as i64];"
    print "    let code = (byte >> ((c & 3) * 2) as u8) & 3;"
    print "    if code == 3 { -1 } else { code as i64 }"
    print "}"
    print ""
    printf "const STAGE1: [u8; 4352] = ["
    for (b = 0; b < 4352; b++) {
        if (b % 24 == 0) printf "\n    "
        printf "%d,%s", stage1[b], (b % 24 == 23 || b == 4351) ? "" : " "
    }
    print "\n];"
    print ""
    printf "const STAGE2: [u8; %d] = [", nblocks * 64
    n = 0
    for (b = 0; b < nblocks; b++)
        for (k = 0; k < 64; k++) {
            if (n % 20 == 0) printf "\n    "
            printf "%d,%s", blockbytes[b, k], (n % 20 == 19 || n == nblocks * 64 - 1) ? "" : " "
            n++
        }
    print "\n];"
}' >"$HERE/../term/width.tach"
echo "wrote examples/voltty/core/term/width.tach"
