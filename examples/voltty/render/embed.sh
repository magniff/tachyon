#!/bin/sh
# Writes render/cells.vl from render/cells.wgsl: the shader's text as a
# constant (vole has no include_str yet). Run it after editing
# cells.wgsl; tests/voltty-render/run.sh checks that the two agree.
#
# usage: examples/voltty/render/embed.sh [--check]
set -eu
LC_ALL=C
export LC_ALL
HERE=$(cd "$(dirname "$0")" && pwd)
out=$(mktemp "${TMPDIR:-/tmp}/cells.XXXXXX")
trap 'rm -f "$out"' EXIT
{
    echo "// Generated by render/embed.sh from render/cells.wgsl (do not edit):"
    echo "// the terminal's shader, compiled at run time by std::gpu::wgsl."
    echo
    printf 'pub const CELLS_WGSL: [u8] = "'
    # comments and blank lines dropped; each line ends in \n and a
    # continuation (which skips the next line's indentation)
    sed -e 's|^[ ]*//.*$||' -e '/^[ ]*$/d' "$HERE/cells.wgsl" \
        | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' \
        | awk 'NR > 1 { printf "\\n\\\n    " } { printf "%s", $0 } END { printf "\\n\";\n" }'
} >"$out"
if [ "${1:-}" = --check ]; then
    cmp -s "$out" "$HERE/cells.vl" || {
        echo "render/cells.vl is not render/cells.wgsl's: run examples/voltty/render/embed.sh" >&2
        exit 1
    }
else
    cp "$out" "$HERE/cells.vl"
fi
