#!/bin/sh
# Makes compiler/src/stdsrc.tach from compiler/std/std.tach: the standard
# library's source, built into the compiler as a function that writes it
# to a buffer (string literals cannot span lines, so one call per line).
# Run it after changing std.tach; tests/run.sh checks they agree.
#
# usage: compiler/std/embed.sh [-c]   (-c: only check, exit 1 if stale)
set -eu
cd "$(dirname "$0")/../.."
out=compiler/src/stdsrc.tach
tmp=$(mktemp)
{
    echo "// Generated by compiler/std/embed.sh from compiler/std/std.tach (do not"
    echo "// edit): the standard library's source (0.5), read when a program names"
    echo "// \`std\` (modules.tach)."
    echo ""
    echo "use crate::base::buf_str;"
    echo ""
    echo "pub fn std_source(out: i64) {"
    echo "    unsafe {"
    # (sed, not awk: awks differ on backslashes in replacements.)
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/        buf_str(out, c"/' -e 's/$/\\n");/' compiler/std/std.tach
    echo "    }"
    echo "}"
} >"$tmp"
if [ "${1:-}" = "-c" ]; then
    if cmp -s "$tmp" "$out"; then rm -f "$tmp"; exit 0; fi
    rm -f "$tmp"
    echo "$out is stale: run compiler/std/embed.sh" >&2
    exit 1
fi
mv "$tmp" "$out"
