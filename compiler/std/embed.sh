#!/bin/sh
# Makes compiler/src/front/stdsrc.tach from compiler/std/std.tach and the
# files appended to it, in this order: iter.tach (0.14), io.tach, fmt.tach,
# convert.tach and clone.tach (0.15), alloc.tach (0.16): the standard
# library's source, one module, built into the compiler as a function that
# writes it to a buffer (string literals cannot span lines, so one call per
# line). Its end is front/stdalloc.tach's std_alloc_tail (0.16): Gpa's
# implementation, gpa.tach (std_gpa_source here), and std::CHECK_ALLOC.
# Run it after changing any of them; tests/run.sh checks they agree.
# (0.15) It also writes std_index, the sections' index (index.awk).
#
# usage: compiler/std/embed.sh [-c]   (-c: only check, exit 1 if stale)
set -eu
cd "$(dirname "$0")/../.."
out=compiler/src/front/stdsrc.tach
tmp=$(mktemp)
files="std iter io fmt convert clone alloc"
# (sed, not awk: awks differ on backslashes in replacements.)
lines() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/        buf_str(out, c"/' -e 's/$/\\n");/'
}
{
    echo "// Generated by compiler/std/embed.sh from compiler/std/std.tach,"
    echo "// iter.tach, io.tach, fmt.tach, convert.tach, clone.tach, alloc.tach"
    echo "// and gpa.tach (do not edit): the standard library's source (0.5),"
    echo "// read when a program names \`std\` (modules.tach)."
    echo ""
    echo "use crate::base::buf_str;"
    echo "use crate::front::stdalloc::std_alloc_tail;"
    echo ""
    echo "pub fn std_source(out: i64) {"
    echo "    unsafe {"
    for f in $files; do cat "compiler/std/$f.tach"; done | lines
    echo "    }"
    echo "    std_alloc_tail(out);"
    echo "}"
    echo ""
    echo "// Gpa's implementation (0.16), the end of std's source unless"
    echo "// --check-alloc (front/stdalloc.tach)."
    echo "pub fn std_gpa_source(out: i64) {"
    echo "    unsafe {"
    lines <compiler/std/gpa.tach
    echo "    }"
    echo "}"
    echo ""
    echo "// (0.15) The index of std's sections (compiler/std/index.awk): what"
    echo "// each defines and needs, so that a program's loader lexes only the"
    echo "// sections it can reach (front/modules: load_std_sections)."
    echo "pub fn std_index(out: i64) {"
    echo "    unsafe {"
    # (0.16: over std_source's whole text, std_alloc_tail's included: Gpa's
    # implementation and CHECK_ALLOC as without --check-alloc)
    { for f in $files; do cat "compiler/std/$f.tach"; done; cat compiler/std/gpa.tach
        echo "pub const CHECK_ALLOC: bool = false;"; } | LC_ALL=C awk -f compiler/std/index.awk |
        grep -v '^#' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/        buf_str(out, c"/' -e 's/$/\\n");/'
    echo "    }"
    echo "}"
} >"$tmp"
if [ "${1:-}" = "-c" ]; then
    if cmp -s "$tmp" "$out"; then rm -f "$tmp"; exit 0; fi
    rm -f "$tmp"
    echo "$out is stale: run compiler/std/embed.sh" >&2
    exit 1
fi
mv "$tmp" "$out"
