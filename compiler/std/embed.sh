#!/bin/sh
# Makes compiler/src/front/stdsrc.tach from compiler/std/std.tach and (0.14)
# compiler/std/iter.tach, appended to it: the standard library's source, one
# module, built into the compiler as a function that writes it to a buffer
# (string literals cannot span lines, so one call per line).
# Run it after changing either file; tests/run.sh checks they agree.
#
# usage: compiler/std/embed.sh [-c]   (-c: only check, exit 1 if stale)
set -eu
cd "$(dirname "$0")/../.."
out=compiler/src/front/stdsrc.tach
tmp=$(mktemp)
{
    echo "// Generated by compiler/std/embed.sh from compiler/std/std.tach and"
    echo "// compiler/std/iter.tach (do not edit): the standard library's source"
    echo "// (0.5), read when a program names \`std\` (modules.tach)."
    echo ""
    echo "use crate::base::buf_str;"
    echo ""
    echo "pub fn std_source(out: i64) {"
    echo "    unsafe {"
    # (sed, not awk: awks differ on backslashes in replacements.)
    cat compiler/std/std.tach compiler/std/iter.tach |
        sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/        buf_str(out, c"/' -e 's/$/\\n");/'
    echo "    }"
    echo "}"
} >"$tmp"
if [ "${1:-}" = "-c" ]; then
    if cmp -s "$tmp" "$out"; then rm -f "$tmp"; exit 0; fi
    rm -f "$tmp"
    echo "$out is stale: run compiler/std/embed.sh" >&2
    exit 1
fi
mv "$tmp" "$out"
