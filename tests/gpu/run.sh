#!/bin/sh
# The tests of std::gpu and std::objc (0.22, docs/design/gpu.md §4),
# headless:
#
# - every tests/gpu/cases/*.tach is compiled with tests/gpu/support.tach
#   and `-l objc` (std::objc opens the frameworks at run time), run under
#   Metal's API and shader validation (MTL_DEBUG_LAYER,
#   MTL_SHADER_VALIDATION), checked, and run again under `leaks --atExit`,
#   which must find nothing;
# - objcgen: every table of compiler/std/objc/tables is regenerated and
#   compared
#   with its checked-in module, checked against the Objective-C runtime
#   (--check) and its constants and structs against the SDK's headers
#   (--c-check, clang -fsyntax-only);
# - the reference images (tests/gpu/ref/*.ppm) are regenerated by the CPU
#   rasterizer (tests/gpu/refgen.tach) and compared with the checked-in
#   ones: a reference is never written by the GPU under test.
#
# usage: tests/gpu/run.sh [-c COMPILER] [-O LEVEL] [-j JOBS] [FILTER]
#
# Directives, in `//` comments of a case:
#   // EXPECT: text     expected stdout, one directive per line
#   // EXIT: n          expected exit status (default 0); a case that is
#                       expected to fail is not run under leaks
#   // STDERR: text     stderr contains text, one directive per line
#   // NEEDS: metal     (every case) skipped, never passed, without Metal
#   // NO-LEAKS: why    not run under leaks
#
# Output: one line per case, `pass NAME`, `skip NAME: why` or `FAIL NAME`
# with the reasons indented below, then a summary line. Exit 1 on a FAIL.
# On hosts other than macOS on arm64 everything is skipped.

set -u
LC_ALL=C
export LC_ALL
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
COMPILER="$ROOT/target/tachyonc"
OPT=""
JOBS=""
CC=${CC:-cc}
while [ $# -gt 0 ]; do
    case "$1" in
        -c) COMPILER=$2; shift 2 ;;
        -O) OPT="-O$2"; shift 2 ;;
        -j) JOBS=$2; shift 2 ;;
        -h|--help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
        -*) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
        *) break ;;
    esac
done
FILTER=${1:-}
case "$COMPILER" in
    /*) ;;
    *) COMPILER="$(pwd)/$COMPILER" ;;
esac

if [ "$(uname -s)-$(uname -m)" != "Darwin-arm64" ]; then
    echo "skip gpu: Metal tests need macOS on arm64"
    exit 0
fi
[ -x "$COMPILER" ] || { echo "gpu/run.sh: no compiler at $COMPILER (use -c)" >&2; exit 2; }
if [ -z "$JOBS" ]; then
    JOBS=$(sysctl -n hw.ncpu 2>/dev/null || echo 4)
fi

WORK=$(mktemp -d "${TMPDIR:-/tmp}/tachyon-gpu.XXXXXX")
trap 'rm -rf "$WORK"' EXIT INT TERM
LINK="-l objc"

# The tools: objcgen and refgen.
mkdir -p "$WORK/tools"
TOOLS_OK=1
if ! "$COMPILER" $OPT "$ROOT/tools/objcgen/main.tach" $LINK -o "$WORK/tools/objcgen" >"$WORK/tools/objcgen.log" 2>&1; then
    TOOLS_OK=0
fi
REFGEN_OK=1
if ! "$COMPILER" $OPT "$ROOT/tests/gpu/refgen.tach" "$ROOT/tests/gpu/support.tach" $LINK -o "$WORK/tools/refgen" >"$WORK/tools/refgen.log" 2>&1; then
    REFGEN_OK=0
fi

# directive FILE KEY: the values of `// KEY: value` lines, one per line.
directive() {
    sed -n "s|^[[:space:]]*// $2: \{0,1\}||p" "$1"
}

run_case() {
    file=$1
    name=$(basename "$file" .tach)
    dir="$WORK/$name"
    mkdir -p "$dir"
    why="$dir/why"
    : >"$why"
    if ! "$COMPILER" $OPT --deny-warnings "$file" "$ROOT/tests/gpu/support.tach" $LINK -o "$dir/prog" >"$dir/build" 2>&1; then
        { echo "build failed:"; sed 's/^/    /' "$dir/build" | head -20; } >>"$why"
        echo fail >"$dir/status"
        return
    fi
    # (the outer 2>/dev/null: the shell's "Abort trap" line for a case
    # that is expected to abort)
    (cd "$ROOT" && MTL_DEBUG_LAYER=1 MTL_SHADER_VALIDATION=1 "$dir/prog" >"$dir/out" 2>"$dir/err") 2>/dev/null
    status=$?
    want_exit=$(directive "$file" EXIT | head -1)
    [ -n "$want_exit" ] || want_exit=0
    if [ "$status" != "$want_exit" ]; then
        { echo "exit status $status, expected $want_exit; stderr:"; grep -v 'Validation Enabled' "$dir/err" | sed 's/^/    /' | head -20; } >>"$why"
    fi
    directive "$file" EXPECT >"$dir/expect"
    sed 's/[[:space:]]*$//' "$dir/out" >"$dir/out.trim"
    if ! cmp -s "$dir/expect" "$dir/out.trim"; then
        { echo "stdout differs (expected, then got):"; sed 's/^/    < /' "$dir/expect"; sed 's/^/    > /' "$dir/out.trim"; } >>"$why"
    fi
    directive "$file" STDERR | while IFS= read -r line; do
        grep -qF -- "$line" "$dir/err" || echo "stderr lacks: $line" >>"$why"
    done
    # API or shader validation failures
    if grep -q -E 'failed assertion|Metal API Validation.*error|validation error' "$dir/err"; then
        { echo "Metal validation:"; grep -E 'failed assertion|error' "$dir/err" | sed 's/^/    /' | head -10; } >>"$why"
    fi
    if [ "$want_exit" = 0 ] && [ -z "$(directive "$file" NO-LEAKS)" ] && [ ! -s "$why" ]; then
        (cd "$ROOT" && leaks --atExit -- "$dir/prog" >"$dir/leaks" 2>&1)
        if ! grep -q ': 0 leaks for 0 total leaked bytes' "$dir/leaks"; then
            { echo "leaks --atExit:"; grep -E 'leaks for|Leak:' "$dir/leaks" | sed 's/^/    /' | head -10; } >>"$why"
        fi
    fi
    if [ -s "$why" ]; then echo fail >"$dir/status"; else echo pass >"$dir/status"; fi
}

# The cases, JOBS at a time.
: >"$WORK/cases"
for f in "$ROOT"/tests/gpu/cases/*.tach; do
    n=$(basename "$f" .tach)
    case "$n" in
        *"$FILTER"*) echo "$f" >>"$WORK/cases" ;;
    esac
done
running=0
while read -r f; do
    run_case "$f" &
    running=$((running + 1))
    if [ "$running" -ge "$JOBS" ]; then
        wait
        running=0
    fi
done <"$WORK/cases"
wait

fails=0
passes=0
report() {
    # report NAME STATUS WHYFILE
    if [ "$2" = pass ]; then
        echo "pass $1"
        passes=$((passes + 1))
    else
        echo "FAIL $1"
        sed 's/^/    /' "$3"
        fails=$((fails + 1))
    fi
}
while read -r f; do
    n=$(basename "$f" .tach)
    st=fail
    [ -f "$WORK/$n/status" ] && st=$(cat "$WORK/$n/status")
    report "$n" "$st" "$WORK/$n/why"
done <"$WORK/cases"

# objcgen: generation, the runtime check, the header check.
case objcgen in
*"$FILTER"*)
    for t in "$ROOT"/compiler/std/objc/tables/*.objc; do
        tn=$(basename "$t" .objc)
        why="$WORK/objcgen-$tn.why"
        : >"$why"
        if [ "$TOOLS_OK" != 1 ]; then
            { echo "objcgen did not build:"; sed 's/^/    /' "$WORK/tools/objcgen.log" | head -20; } >>"$why"
        else
            out=$(sed -n 's/^# Generated into \([^ ]*\) .*/\1/p' "$t" | head -1)
            [ -n "$out" ] || out=$(sed -n 's/^# \{0,1\}.*generated into \([^ ]*\) by.*/\1/p' "$t" | head -1)
            (cd "$ROOT" && "$WORK/tools/objcgen" "compiler/std/objc/tables/$tn.objc") >"$WORK/gen-$tn.tach" 2>>"$why"
            if [ -z "$out" ]; then
                echo "the table names no 'Generated into PATH' line" >>"$why"
            elif ! cmp -s "$WORK/gen-$tn.tach" "$ROOT/$out"; then
                echo "$out is not what objcgen makes of compiler/std/objc/tables/$tn.objc (regenerate it, then compiler/std/embed.sh)" >>"$why"
            fi
            (cd "$ROOT" && "$WORK/tools/objcgen" --check "compiler/std/objc/tables/$tn.objc") >/dev/null 2>"$WORK/check-$tn.err" ||
                { echo "objcgen --check:"; sed 's/^/    /' "$WORK/check-$tn.err"; } >>"$why"
            (cd "$ROOT" && "$WORK/tools/objcgen" --c-check "compiler/std/objc/tables/$tn.objc") >"$WORK/c-check-$tn.m" 2>>"$why"
            clang -fsyntax-only -x objective-c "$WORK/c-check-$tn.m" >"$WORK/c-check-$tn.err" 2>&1 ||
                { echo "objcgen --c-check (clang):"; grep 'error' "$WORK/c-check-$tn.err" | sed 's/^/    /' | head -10; } >>"$why"
        fi
        if [ -s "$why" ]; then report "objcgen-$tn" fail "$why"; else report "objcgen-$tn" pass "$why"; fi
    done
    ;;
esac

# (design §2.4, D9) Encoding and submitting allocate nothing from Gpa:
# `query effects --has alloc(Gpa)` over the per-frame functions prints
# nothing (their scratch is fixed arrays; creation is what allocates).
case noalloc in
*"$FILTER"*)
    why="$WORK/noalloc.why"
    : >"$why"
    printf 'use std::gpu;\nfn main(gpa: Gpa) {\n    let _i = gpu::Instance::new_in(gpa);\n}\n' >"$WORK/noalloc.tach"
    for f in std::gpu::Device::encoder std::gpu::Device::bind_group std::gpu::Encoder::compute_pass std::gpu::Encoder::render_pass \
             std::gpu::Encoder::copy_buffer std::gpu::Encoder::copy_texture_to_buffer std::gpu::Encoder::finish \
             std::gpu::ComputePass::set_pipeline std::gpu::ComputePass::set_bind_group std::gpu::ComputePass::dispatch \
             std::gpu::RenderPass::set_pipeline std::gpu::RenderPass::set_bind_group std::gpu::RenderPass::set_vertex_buffer \
             std::gpu::RenderPass::draw std::gpu::RenderPass::draw_indexed std::gpu::Queue::submit std::gpu::Queue::write_buffer \
             std::gpu::Buffer::map_read std::gpu::Surface::frame std::gpu::Frame::present; do
        out=$("$COMPILER" query effects --has 'alloc(Gpa)' "$f" --root "$WORK/noalloc.tach" 2>&1)
        case "$out" in
            *query.empty*) ;;
            *) echo "$f allocates from Gpa: $out" >>"$why" ;;
        esac
    done
    # (and the query sees what does allocate: shader creation copies names)
    out=$("$COMPILER" query effects --has 'alloc(Gpa)' std::gpu::Device::shader --root "$WORK/noalloc.tach" 2>&1)
    case "$out" in
        *"std::gpu::Device::shader"*) ;;
        *) echo "query effects did not find Device::shader's allocation: $out" >>"$why" ;;
    esac
    if [ -s "$why" ]; then report noalloc fail "$why"; else report noalloc pass "$why"; fi
    ;;
esac

# The reference images.
case refgen in
*"$FILTER"*)
    why="$WORK/refgen.why"
    : >"$why"
    if [ "$REFGEN_OK" != 1 ]; then
        { echo "refgen did not build:"; sed 's/^/    /' "$WORK/tools/refgen.log" | head -20; } >>"$why"
    else
        mkdir -p "$WORK/ref"
        "$WORK/tools/refgen" "$WORK/ref" >/dev/null 2>>"$why" || echo "refgen failed" >>"$why"
        for r in "$WORK"/ref/*.ppm; do
            [ -f "$r" ] || continue
            b=$(basename "$r")
            cmp -s "$r" "$ROOT/tests/gpu/ref/$b" || echo "tests/gpu/ref/$b is not what tests/gpu/refgen.tach draws (regenerate: see refgen.tach)" >>"$why"
        done
        for r in "$ROOT"/tests/gpu/ref/*.ppm; do
            [ -f "$r" ] || continue
            [ -f "$WORK/ref/$(basename "$r")" ] || echo "tests/gpu/ref/$(basename "$r") is no longer drawn by refgen" >>"$why"
        done
    fi
    if [ -s "$why" ]; then report refgen fail "$why"; else report refgen pass "$why"; fi
    ;;
esac

echo "gpu: $passes passed, $fails failed"
[ "$fails" = 0 ]
