#!/bin/sh
# The test of `tachyonc fmt` (0.13): the tree is formatted, and formatting
# changes no program's meaning. POSIX sh and awk only.
#
# usage: tests/fmt/run.sh [-c COMPILER] [-j JOBS]
#
#   tree        `tachyonc fmt --all --check` from the root: every .tach of
#               compiler/, tests/, examples/ and bench/ is formatted (but
#               the ones fmt leaves as they are: not lexed, unbalanced
#               brackets, conflict markers, generated; and the programs of
#               the tools' transcript tests, tests/query/ and
#               tests/refactor/, whose text is what they test)
#   roundtrip   a copy of those directories with every line's
#               indentation removed (but a string's continuation lines),
#               formatted: compiler/src and compiler/std come back byte
#               for byte (the fixpoint), and so does every file of the
#               rest that has no block comment
#   compiles    every program of the corpus (tests/run, examples, bench,
#               compiler/src) compiled at -O2 from the tree and from the
#               copy: the same assembly, exit status and messages (their
#               positions and the compiler's path aside)
#   same-output the compiler built from the copy's compiler/src: the same
#               object as the one built from the tree's, and `same-output`
#               against it: identical
#
# Prints `pass NAME` or `FAIL NAME` (and why) for each; exits 1 if one
# failed.

set -u
LC_ALL=C
export LC_ALL

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
COMPILER="$ROOT/target/tachyonc"
JOBS=2
while [ $# -gt 0 ]; do
    case "$1" in
        -c) [ $# -ge 2 ] || exit 2; COMPILER=$2; shift 2 ;;
        -j) [ $# -ge 2 ] || exit 2; JOBS=$2; shift 2 ;;
        *) echo "usage: tests/fmt/run.sh [-c COMPILER] [-j JOBS]" >&2; exit 2 ;;
    esac
done
case "$COMPILER" in
    /*) ;;
    *) COMPILER="$(pwd)/$COMPILER" ;;
esac
[ -x "$COMPILER" ] || { echo "fmt/run.sh: no compiler at $COMPILER" >&2; exit 2; }

WORK=$(mktemp -d "${TMPDIR:-/tmp}/tachyon-fmt.XXXXXX")
WORK=$(cd "$WORK" && pwd -P)
trap 'rm -rf "$WORK"' EXIT
trap 'exit 130' INT TERM
STATUS=0
check() { # <name> <ok> <why>
    if [ "$2" = 1 ]; then
        echo "pass $1"
    else
        echo "FAIL $1:"
        printf '%s\n' "$3" | head -20 | sed 's/^/    /'
        STATUS=1
    fi
}
cd "$ROOT" || exit 2

# tree
"$COMPILER" fmt --all --check >"$WORK/check.out" 2>&1
rc=$?
check tree "$([ $rc = 0 ] && echo 1)" "$(cat "$WORK/check.out")"

# roundtrip
COPY="$WORK/copy"
mkdir -p "$COPY"
cp -R compiler tests examples bench "$COPY/"
find compiler/src compiler/std tests examples bench -name '*.tach' \
    | grep -v '^tests/query/' | grep -v '^tests/refactor/' | sort >"$WORK/files"
while IFS= read -r f; do
    head -1 "$f" | grep -q '^// Generated by' && continue
    awk '{ if (!cont) sub(/^[ \t]+/, ""); print; cont = /\\$/ }' "$f" >"$COPY/$f"
done <"$WORK/files"
(cd "$COPY" && "$COMPILER" fmt --all) >"$WORK/fmt.out" 2>&1
# (a file fmt leaves as it is, not lexed or unbalanced, stays dedented)
: >"$WORK/differs"
while IFS= read -r f; do
    cmp -s "$f" "$COPY/$f" && continue
    "$COMPILER" fmt "$f" --check 2>&1 | grep -q '^error fmt.unreadable' && continue
    case "$f" in
        compiler/*) echo "$f" >>"$WORK/differs" ;;
        *) grep -q '/\*' "$f" || echo "$f" >>"$WORK/differs" ;;
    esac
done <"$WORK/files"
n=$(wc -l <"$WORK/differs" | tr -d ' ')
check roundtrip "$([ "$n" = 0 ] && echo 1)" \
    "$n files differ after a round trip: $(head -5 "$WORK/differs" | tr '\n' ' ')
$(cat "$WORK/fmt.out")"

# compiles
# (examples/tools/ has its own runner, and programs that do not compile)
programs=$(ls tests/run/*.tach tests/run/*/main.tach examples/*/main.tach examples/*/*/main.tach bench/*.tach 2>/dev/null | grep -v '^examples/tools/')
mkdir -p "$WORK/c"
printf '%s\n' $programs compiler/src/main.tach | awk -v w="$WORK/c" '{ print NR " " $0 }' >"$WORK/list"
compile_one() { # <n> <program>
    d="$WORK/c/$1"
    mkdir -p "$d"
    # (0.18.1: without the success line, which names the output)
    TACHYON_OK=0 "$COMPILER" --diagnostics=human -O2 -S "$ROOT/$2" -o "$d/a.s" >"$d/a.out" 2>&1
    echo $? >"$d/a.rc"
    TACHYON_OK=0 "$COMPILER" --diagnostics=human -O2 -S "$COPY/$2" -o "$d/b.s" >"$d/b.out" 2>&1
    echo $? >"$d/b.rc"
    # (0.17: try: lines start with the compiler as it was run, and name
    # positions as FILE:LINE and `the arm at line N`)
    sed -e "s|$COMPILER|tachyonc|g" -e "s|$ROOT/||g" -e 's|line [0-9]*, column [0-9]*|POS|g' \
        -e 's|\.tach:[0-9][0-9]*|.tach:N|g' -e 's|at line [0-9]*|at line N|g' "$d/a.out" >"$d/a.msg"
    sed -e "s|$COMPILER|tachyonc|g" -e "s|$COPY/||g" -e 's|line [0-9]*, column [0-9]*|POS|g' \
        -e 's|\.tach:[0-9][0-9]*|.tach:N|g' -e 's|at line [0-9]*|at line N|g' "$d/b.out" >"$d/b.msg"
    # (0.18: the run-time checks' messages and sites hold positions and the
    # conditions' text: from rt.messages to the next label that is not the
    # helper's, left out)
    for s in a b; do
        [ -f "$d/$s.s" ] && awk '/rt\.messages:$/ { skip = 1; next }
            skip && /^[^ \t].*:$/ && !/rt\./ { skip = 0 } !skip' "$d/$s.s" >"$d/$s.t" && mv "$d/$s.t" "$d/$s.s"
    done
    if cmp -s "$d/a.rc" "$d/b.rc" && cmp -s "$d/a.msg" "$d/b.msg" \
        && { [ ! -f "$d/a.s" ] || cmp -s "$d/a.s" "$d/b.s"; }; then
        echo same >"$d/result"
    else
        echo "$2" >"$d/result"
    fi
    rm -f "$d/a.s" "$d/b.s"
}
i=0
while read -r k p; do
    compile_one "$k" "$p" &
    i=$((i + 1))
    [ $((i % JOBS)) = 0 ] && wait
done <"$WORK/list"
wait
total=$(wc -l <"$WORK/list" | tr -d ' ')
bad=$(cat "$WORK"/c/*/result | grep -v '^same$')
check compiles "$([ -z "$bad" ] && [ "$(cat "$WORK"/c/*/result | wc -l | tr -d ' ')" = "$total" ] && echo 1)" \
    "$total programs; differ: $bad"

# same-output
ok=0
"$COMPILER" compiler/src/main.tach -c -o "$WORK/old.o" >/dev/null 2>&1
(cd "$COPY" && "$COMPILER" compiler/src/main.tach -c -o "$WORK/new.o") >/dev/null 2>&1
${CC:-cc} -o "$WORK/new-tachyonc" "$WORK/new.o" -lm 2>/dev/null
out=$("$WORK/new-tachyonc" same-output "$COMPILER" --corpus examples --work "$WORK/so" 2>&1)
cmp -s "$WORK/old.o" "$WORK/new.o" && printf '%s\n' "$out" | grep -q '^identical' && ok=1
check same-output "$ok" "$out"
exit $STATUS
